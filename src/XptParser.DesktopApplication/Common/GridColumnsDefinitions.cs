namespace XptParser.DesktopApplication
{
    /// <summary>
    /// Provides predefined grid column indices.
    /// </summary>
    public static class GridColumnsDefinitions
    {
        /// <summary>
        /// Represents the zero-based index of the first column.
        /// </summary>
        public static int Zero { get; } = 0;

        /// <summary>
        /// Represents the index of the first column.
        /// </summary>
        public static int First { get; } = 1;

        /// <summary>
        /// Represents the index of the second column.
        /// </summary>
        public static int Second { get; } = 2;
    }
}